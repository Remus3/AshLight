ARCHIVE = "a" * 64


def test_parser_keeps_explicit_rows_only():
    idx = tradestats.parse_pob_trade_stats(FIXTURE)
    assert idx == {
        "#% to fire resistance": "explicit.stat_9000001",
        "# to strength": "explicit.stat_9000002",
        "# to maximum life": "explicit.stat_9000003",
        "#% increased armour": "explicit.stat_8000005",  # lowest id wins
    }
    # weights keys match through the same exact norm
    assert tradestats.lookup(idx, "+#% to Fire Resistance") == "explicit.stat_9000001"
    assert tradestats.lookup(idx, "+# to Strength") == "explicit.stat_9000002"
    assert tradestats.lookup(idx, "#% increased Evasion Rating") is None
    assert tradestats.lookup(idx, "#% increased Movement Speed") is None


def test_parser_bounds_and_junk():
    assert tradestats.parse_pob_trade_stats(None) == {}
    assert tradestats.parse_pob_trade_stats("return {}") == {}
    big = "\n" * (tradestats.POB_MAX_LINES + 1)
    assert tradestats.parse_pob_trade_stats(big) == {}
    # a fuzzy near-miss text never maps
    idx = tradestats.parse_pob_trade_stats(FIXTURE)
    assert tradestats.lookup(idx, "+#% to Fire Resistances") is None


def test_merge_repoe_wins_and_reports_conflicts():
    primary = {"# to maximum life": "explicit.stat_1"}
    fallback = tradestats.parse_pob_trade_stats(FIXTURE)
    idx, conflicts = tradestats.merge(primary, fallback)
    assert idx["# to maximum life"] == "explicit.stat_1"
    assert idx["# to strength"] == "explicit.stat_9000002"
    assert conflicts == ["# to maximum life"]
    same, none = tradestats.merge({"# to strength": "explicit.stat_9000002"}, fallback)
    assert none == [] and same["# to strength"] == "explicit.stat_9000002"
    assert tradestats.merge(None, None) == ({}, [])


def _install(tmp_path, text=FIXTURE, archive=ARCHIVE):
    root = tmp_path / "pob2" / "Top-1"
    lua = root / tradestats.POB_REL
    lua.parent.mkdir(parents=True)
    lua.write_text(text, encoding="utf-8", newline="\n")
    (root / tradestats.POB_MARKER).write_text(
        json.dumps({"archive_sha256": archive, "component": "pob2"}), encoding="ascii")
    pins = {"pob2": {"top_dir": "Top-1", "archive_sha256": ARCHIVE},
            "pob2_files": {tradestats.POB_REL: {
                "sha256": hashlib.sha256(lua.read_bytes()).hexdigest()}}}
    return lua, pins


def test_load_requires_marker_and_file_hash(tmp_path):
    lua, pins = _install(tmp_path)
    assert tradestats.load_pob_index(lua, pins)["# to strength"] == "explicit.stat_9000002"
    # file edited after the pin: refused
    lua.write_text(FIXTURE + "\n", encoding="utf-8", newline="\n")
    assert tradestats.load_pob_index(lua, pins) == {}
    # marker names another archive: refused
    lua2, pins2 = _install(tmp_path / "b", archive="b" * 64)
    assert tradestats.load_pob_index(lua2, pins2) == {}
    # no file pin, malformed pin, missing file: refused
    assert tradestats.load_pob_index(lua2, {"pob2": pins2["pob2"]}) == {}
    lua3, pins3 = _install(tmp_path / "c")
    pins3["pob2_files"][tradestats.POB_REL]["sha256"] = "XYZ"
    assert tradestats.load_pob_index(lua3, pins3) == {}
    assert tradestats.load_pob_index(tmp_path / "nope" / tradestats.POB_REL, pins) == {}


def test_load_size_cap(tmp_path, monkeypatch):
    lua, pins = _install(tmp_path)
    monkeypatch.setattr(tradestats, "POB_MAX_BYTES", 100)
    assert tradestats.load_pob_index(lua, pins) == {}


def test_index_cache_fallback_fills_only_missing(tmp_path, caplog):
    lua, pins = _install(tmp_path)
    repoe = tmp_path / tradestats.FILE_NAME
    repoe.write_text(json.dumps([{"trade_stats": [
        {"id": "explicit.stat_1", "text": "# to maximum Life", "type": "explicit"}]}]),
        encoding="utf-8")
    with caplog.at_level(logging.WARNING, logger="al.tradestats"):
        cache = tradestats.IndexCache(repoe, pob=(lua, pins))
        idx = cache.get()
    assert idx["# to maximum life"] == "explicit.stat_1"
    assert idx["#% to fire resistance"] == "explicit.stat_9000001"
    assert cache.conflicts == ["# to maximum life"]
    assert "repoe-fork kept" in caplog.text
    # without the component the index is repoe-fork's alone
    assert tradestats.IndexCache(repoe).get() == {"# to maximum life": "explicit.stat_1"}
    # repoe file missing: the verified fallback still serves
    assert tradestats.IndexCache(tmp_path / "missing.json", pob=(lua, pins)).get()[
        "# to strength"] == "explicit.stat_9000002"
    # neither source: empty
    assert tradestats.IndexCache(tmp_path / "missing.json").get() == {}


def test_pob_source_rejects_odd_top_dir(tmp_path, monkeypatch):
    monkeypatch.setenv("AL_SIDECAR_ROOT", str(tmp_path))
    path, doc = tradestats.pob_source(pins={"pob2": {"top_dir": "Top-1"}})
    assert path.parts[-4:] == ("Top-1", "src", "Data", "TradeSiteStats.lua")
    assert tradestats.pob_source(pins={"pob2": {"top_dir": "../x"}}) == (None, None)
    assert tradestats.pob_source(pins={}) == (None, None)
