"""SEC-DEMO-ENTRY (decision 0049): `python -m server.al --demo <fixture dir>`
starts the real core process as an isolated demo instance on a fixture
folder. The end-to-end tests start that process with a tmp AL_SIDECAR_ROOT
and --port 0 (never 8960), read its URL line, ask /api/health, check that
its tailer reads the fixture's Client.txt and that its token, heartbeat and
core.log exist only under its scratch folder, and that the live token file
and config/local.json keep their size and mtime.

The tracked fixture (tests/fixtures/demo) is synthetic: its Client.txt is
exactly fixture_text() below, built with tools/synth_client.py (synthetic
names, ASCII, LF). Regenerate it with:

    python tests/test_demo_entry.py --write
"""

import json
import os
import queue
import re
import subprocess
import sys
import threading
import time
import urllib.request
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "tools"))
sys.path.insert(0, str(ROOT))

import synth_client  # noqa: E402
from server.al import demo, paths, ports  # noqa: E402

pytestmark = pytest.mark.server

FIXTURE = ROOT / "tests" / "fixtures" / "demo"
SEED = 49
CHARACTER = "Demowisp"
KLASS = "Sorceress"
URL_RE = re.compile(r"http://127\.0\.0\.1:(\d+)/#token=([0-9A-Za-z_\-]+)")
SCRATCH_RE = re.compile(r"^demo mode: fixture .+; scratch (.+)$")
START_S = 60.0
STOP_S = 30.0


# ------------------------------------------------------------ the fixture

def fixture_lines():
    """The demo Client.txt lines: one short leveling session through the
    first zones (level-ups, two deaths, a whisper, a trade and its
    acceptance, chat and engine noise). Deterministic from SEED."""
    s = synth_client.Session(seed=SEED, character=CHARACTER, klass=KLASS)
    s.marker()
    s.raw("[WINDOW] Gained focus")
    for area_id, level, name in synth_client.ZONES:
        s.zone_change(area_id, level, name)
        s.noise(2)
        s.level_up()
        s.chat("#", "Chatterbox", "anyone know a good leveling build")
    s.death()
    s.whisper("Wanderer", "hello there, nice build")
    s.trade_whisper("Tradewind", "Grim Bane Ruby Ring", 5, "exalted")
    s.trade_accepted()
    s.whisper_out("Tradewind", "thanks, have fun")
    s.zone_change(*synth_client.ZONES[2])
    s.death()
    return s.lines


def fixture_text():
    return "".join(line + "\n" for line in fixture_lines())


def marker_doc():
    return {"ashlight_demo": 1,
            "note": "Synthetic demo fixture for AshLight demo mode (decision 0049); "
                    "generated by tests/test_demo_entry.py, no real game data."}


def write_fixture(folder=FIXTURE):
    folder.mkdir(parents=True, exist_ok=True)
    (folder / "Client.txt").write_bytes(fixture_text().encode("ascii"))
    (folder / demo.MARKER).write_bytes(
        (json.dumps(marker_doc(), indent=1) + "\n").encode("ascii"))


# ------------------------------------------------------------ the process

def child_env(sidecar):
    """The test's environment for a demo child: a tmp sidecar root, no
    runtime or port override, a fast heartbeat, no bytecode written."""
    env = {k: v for k, v in os.environ.items()
           if k not in (paths.RUNTIME_ENV, paths.SIDECAR_ENV, ports.PORT_ENV)}
    env[paths.SIDECAR_ENV] = str(sidecar)
    env["AL_HEARTBEAT_S"] = "0.5"
    env["PYTHONDONTWRITEBYTECODE"] = "1"
    env["PYTHONUNBUFFERED"] = "1"
    return env


def run_demo(args, sidecar, timeout=START_S):
    return subprocess.run([sys.executable, "-m", "server.al", *args], cwd=str(ROOT),
                          env=child_env(sidecar), capture_output=True, text=True,
                          encoding="utf-8", errors="replace", timeout=timeout)


class DemoProcess:
    """A real `python -m server.al --demo FIXTURE --port 0` process."""

    def __init__(self, sidecar):
        self.sidecar = sidecar
        self.proc = subprocess.Popen(
            [sys.executable, "-m", "server.al", "--demo", str(FIXTURE), "--port", "0"],
            cwd=str(ROOT), env=child_env(sidecar), stdin=subprocess.DEVNULL,
            stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True,
            encoding="utf-8", errors="replace")
        self.lines = []
        self._q = queue.Queue()
        threading.Thread(target=self._read, daemon=True).start()
        self.port = self.token = self.scratch = None
        deadline = time.monotonic() + START_S
        while (self.port is None or self.scratch is None) and time.monotonic() < deadline:
            try:
                line = self._q.get(timeout=0.5)
            except queue.Empty:
                if self.proc.poll() is not None:
                    break
                continue
            m = URL_RE.search(line)
            if m:
                self.port, self.token = int(m.group(1)), m.group(2)
            m = SCRATCH_RE.match(line.strip())
            if m:
                self.scratch = Path(m.group(1))
        if self.port is None or self.scratch is None:
            self.kill()
            raise AssertionError("no URL / scratch line from the demo process: "
                                 + " | ".join(self.lines[-20:]))

    def _read(self):
        for line in self.proc.stdout:
            self.lines.append(line.rstrip("\n"))
            self._q.put(line)

    def get(self, path):
        req = urllib.request.Request(f"http://{ports.LOOPBACK}:{self.port}{path}",
                                     headers={"X-AL-Token": self.token})
        with urllib.request.urlopen(req, timeout=10) as resp:
            return json.loads(resp.read().decode("utf-8"))

    def wait_for(self, check, what, timeout=START_S):
        deadline = time.monotonic() + timeout
        last = None
        while time.monotonic() < deadline:
            try:
                last = check()
            except OSError as exc:
                last = exc
            else:
                if last:
                    return last
            if self.proc.poll() is not None:
                break
            time.sleep(0.2)
        raise AssertionError(f"{what} never held (last {last!r}): "
                             + " | ".join(self.lines[-20:]))

    def stop(self):
        """A clean stop through the scratch stop.request (scripts/stop.ps1's
        channel); returns the exit code."""
        (self.scratch / "runtime" / "stop.request").write_text("stop\n", encoding="ascii")
        try:
            return self.proc.wait(STOP_S)
        except subprocess.TimeoutExpired:
            self.kill()
            raise AssertionError("the demo process ignored stop.request")

    def kill(self):
        if self.proc.poll() is None:
            self.proc.kill()
            self.proc.wait(STOP_S)


def _stat(path):
    try:
        st = path.stat()
    except FileNotFoundError:
        return None
    return (st.st_size, st.st_mtime_ns)


def live_paths():
    """The live token file and config/local.json of this checkout (resolved
    from the repo path, never from an env override)."""
    return {"token": ROOT / "ops" / "runtime" / "token",
            "config": ROOT / "config" / "local.json"}


def _inside(path, root):
    try:
        Path(os.path.abspath(path)).resolve().relative_to(Path(root).resolve())
        return True
    except ValueError:
        return False


@pytest.fixture(scope="module")
def demo_run(tmp_path_factory):
    """One demo process for the module: its observations while running and
    after a clean stop, plus the live files' stat before and after."""
    base = tmp_path_factory.mktemp("demo_entry")
    sidecar = base / "sidecar"
    before = {k: _stat(p) for k, p in live_paths().items()}
    proc = DemoProcess(sidecar)
    try:
        health = proc.wait_for(lambda: (lambda h: h if h.get("tailing") else None)(
            proc.get("/api/health")), "health with tailing")
        runtime = proc.scratch / "runtime"
        proc.wait_for(lambda: (runtime / "core.alive").is_file(), "heartbeat file")
        state = proc.get("/api/state")
        found = {name: sorted(str(p) for p in base.rglob(name))
                 for name in ("token", "core.alive", "core.log")}
        token_text = (runtime / "token").read_text(encoding="ascii").strip()
        heartbeat = json.loads((runtime / "core.alive").read_text(encoding="ascii"))
        rc = proc.stop()
    finally:
        proc.kill()
    after = {k: _stat(p) for k, p in live_paths().items()}
    return {"base": base, "sidecar": sidecar, "proc": proc, "health": health,
            "state": state, "found": found, "token_text": token_text,
            "heartbeat": heartbeat, "rc": rc, "before": before, "after": after}


# ------------------------------------------------------------ tests

def test_demo_with_a_missing_fixture_exits_non_zero(tmp_path):
    sidecar = tmp_path / "sidecar"
    missing = tmp_path / "no-such-demo"
    r = run_demo(["--demo", str(missing), "--port", "0"], sidecar)
    assert r.returncode != 0, r.stdout + r.stderr
    assert "demo folder not found" in r.stderr
    assert "#token=" not in r.stdout
    assert not sidecar.exists()  # nothing made: no scratch, no logs
    # a folder without the demo marker is refused the same way
    bare = tmp_path / "bare"
    bare.mkdir()
    (bare / "Client.txt").write_text("x\n", encoding="ascii")
    r = run_demo(["--demo", str(bare), "--port", "0"], sidecar)
    assert r.returncode != 0 and demo.MARKER in r.stderr
    assert not sidecar.exists()
    # --log cannot point a demo at another file
    r = run_demo(["--demo", str(FIXTURE), "--log", str(bare / "Client.txt"),
                  "--port", "0"], sidecar)
    assert r.returncode != 0 and "--log" in r.stderr
    assert not sidecar.exists()


def test_demo_process_answers_health_and_stays_in_its_dirs(demo_run):
    proc = demo_run["proc"]
    scratch = proc.scratch
    health = demo_run["health"]
    assert health["ok"] is True and health["tailing"] is True
    assert health["port"] == proc.port and proc.port not in (0, ports.AL_PORT)
    # the scratch folder is <tmp sidecar>/Temp/demo-*
    temp = (demo_run["sidecar"] / "Temp").resolve()
    assert scratch.resolve().parent == temp and scratch.name.startswith(demo.SCRATCH_PREFIX)
    # the tmp sidecar holds only Temp: logs went to the scratch sidecar
    assert sorted(p.name for p in demo_run["sidecar"].iterdir()) == ["Temp"]
    # the tailer reads the fixture's Client.txt
    tailer_path = demo_run["state"]["tailer"].get("path")
    assert tailer_path, demo_run["state"]["tailer"]
    assert _inside(tailer_path, FIXTURE)
    assert Path(tailer_path).name == "Client.txt"
    # token, heartbeat and core.log exist, and only under the scratch folder
    found = demo_run["found"]
    for name in ("token", "core.alive", "core.log"):
        assert found[name], f"no {name} was written"
        assert all(_inside(p, scratch) for p in found[name]), found[name]
    assert found["token"] == [str(scratch / "runtime" / "token")]
    assert found["core.alive"] == [str(scratch / "runtime" / "core.alive")]
    assert found["core.log"] == [str(scratch / "sidecar" / "Logs" / "core.log")]
    assert demo_run["token_text"] == proc.token
    assert demo_run["heartbeat"]["port"] == proc.port
    log_text = (scratch / "sidecar" / "Logs" / "core.log").read_text(encoding="utf-8")
    assert "demo mode: fixture" in log_text
    # the demo consent record covers the fixture file only
    consent = json.loads((scratch / "runtime" / "consent.json").read_text("utf-8"))
    assert consent["demo"] is True and _inside(consent["path"], FIXTURE)
    # a clean stop: exit 0, token and heartbeat removed
    assert demo_run["rc"] == 0
    assert not (scratch / "runtime" / "token").exists()
    assert not (scratch / "runtime" / "core.alive").exists()
    # nothing was written into the fixture folder
    assert sorted(p.name for p in FIXTURE.iterdir()) == ["Client.txt", demo.MARKER]


def test_live_token_and_config_are_untouched(demo_run):
    # the stat of the files themselves, not the ops/runtime folder mtime,
    # which a running live core changes with every heartbeat write
    assert demo_run["after"] == demo_run["before"]
    # the demo's token is not the live one
    live = live_paths()["token"]
    if live.is_file():
        assert live.read_text(encoding="ascii").strip() != demo_run["proc"].token


def test_demo_fixture_is_synthetic_and_ascii():
    log = FIXTURE / "Client.txt"
    data = log.read_bytes()
    data.decode("ascii")
    assert b"\r" not in data
    # synthetic: byte for byte what tools/synth_client.py builds from SEED
    assert data == fixture_text().encode("ascii")
    assert f": {CHARACTER} ({KLASS}) is now level " in data.decode("ascii")
    # the only addresses are documentation-range (RFC 5737) ones
    ips = set(re.findall(r"\b\d+\.\d+\.\d+\.\d+\b", data.decode("ascii")))
    assert ips and all(ip.startswith("192.0.2.") for ip in ips)
    marker = (FIXTURE / demo.MARKER).read_bytes()
    marker.decode("ascii")
    assert b"\r" not in marker
    assert json.loads(marker) == marker_doc()
    # the folder passes demo mode's own checks
    real, found = demo.check_fixture(FIXTURE)
    assert found == real / "Client.txt"
    assert demo.game_path_part(str(real)) is None


